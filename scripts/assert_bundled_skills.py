#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Byte-equality and topology gate for the top-level `skills/` build artifact.

`skills/` is rebuilt wholesale by `scripts/build_skills.py` from one canonical
source:

  * `assets/skills/init` -- the hand-authored init skill

This gate fails CI when:

  * `skills/init` is not byte-identical to `assets/skills/init`
  * the top-level `skills/` set is not exactly `{init}` (any extra entry,
    including a stale `skills/speckit-*` directory, is named)
  * either tree is missing or empty (the gate must never pass vacuously)

Usage:
    uv run scripts/assert_bundled_skills.py
    uv run scripts/assert_bundled_skills.py --repo /path/to/checkout

Exits 2 on drift/dangling/missing copies, 1 when either tree is empty.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

INIT_SOURCE_REL = Path("assets") / "skills" / "init"
BUNDLE_REL = Path("skills")
PREFIX = "speckit-"
INIT_NAME = "init"
REBUILD_HINT = (
    "skills/ is generated by scripts/build_skills.py from assets/skills/init; "
    "edit that source and run 'uv run scripts/build_skills.py' to rebuild."
)


def rel_files(root: Path) -> dict[str, Path]:
    files: dict[str, Path] = {}
    if not root.is_dir():
        return files
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        filenames.sort()
        for name in filenames:
            path = Path(dirpath) / name
            files[path.relative_to(root).as_posix()] = path
    return files


def compare_trees(
    src: Path, dst: Path, label: str, source_rel: Path, bundle_rel: Path
) -> list[str]:
    """Return error messages if `dst` is not a byte-identical copy of `src`."""
    errors: list[str] = []
    src_shown = source_rel.as_posix()
    dst_shown = bundle_rel.as_posix()
    if not src.is_dir():
        errors.append(f"{label}: missing source {src_shown}")
        return errors
    if not dst.is_dir():
        errors.append(
            f"{label}: missing copy {dst_shown} "
            f"(generated from {src_shown}; the copy is generated -- edit the source)"
        )
        return errors

    src_files = rel_files(src)
    dst_files = rel_files(dst)
    only_src = sorted(set(src_files) - set(dst_files))
    only_dst = sorted(set(dst_files) - set(src_files))
    for rel in only_src:
        errors.append(
            f"{label}: missing file {dst_shown}/{rel} "
            f"(generated copy of {src_shown}/{rel})"
        )
    for rel in only_dst:
        errors.append(
            f"{label}: extra file {dst_shown}/{rel} "
            f"(not in canonical source {src_shown}; the copy is generated)"
        )
    for rel in sorted(set(src_files) & set(dst_files)):
        if src_files[rel].read_bytes() != dst_files[rel].read_bytes():
            errors.append(
                f"{label}: byte mismatch {dst_shown}/{rel} "
                f"(generated copy of {src_shown}/{rel}; edit the source, not the copy)"
            )
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--repo",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="repository checkout to inspect (default: this script's repository)",
    )
    args = parser.parse_args(argv)
    repo = args.repo.resolve()

    init_source = repo / INIT_SOURCE_REL
    init_bundle = repo / BUNDLE_REL / INIT_NAME
    bundle_parent = repo / BUNDLE_REL

    errors: list[str] = []

    actual: set[str] = set()
    if bundle_parent.is_dir():
        actual = {child.name for child in bundle_parent.iterdir()}

    dangling = sorted(actual - {INIT_NAME})
    for name in dangling:
        shown = f"{BUNDLE_REL.as_posix()}/{name}"
        if name.startswith(PREFIX):
            errors.append(
                f"denied generated skill: {shown} "
                f"(top-level {BUNDLE_REL.as_posix()}/ must be exactly {{{INIT_NAME}}})"
            )
        else:
            errors.append(
                f"dangling top-level entry: {shown} "
                f"(top-level {BUNDLE_REL.as_posix()}/ must be exactly {{{INIT_NAME}}})"
            )

    if INIT_NAME not in actual:
        errors.append(
            f"missing top-level entry: {BUNDLE_REL.as_posix()}/{INIT_NAME} "
            f"(generated from {INIT_SOURCE_REL.as_posix()})"
        )

    errors.extend(
        compare_trees(init_source, init_bundle, INIT_NAME, INIT_SOURCE_REL, BUNDLE_REL / INIT_NAME)
    )

    if errors:
        print("error: bundled skills drifted from canonical sources:", file=sys.stderr)
        for message in errors:
            print(f"  - {message}", file=sys.stderr)
        print(REBUILD_HINT, file=sys.stderr)
        return 2

    if not rel_files(init_source) or not rel_files(init_bundle):
        print(
            "error: assets/skills/init or skills/init is empty; "
            "the gate must never pass vacuously",
            file=sys.stderr,
        )
        return 1

    print(
        f"ok: {INIT_NAME} byte-identical "
        f"({BUNDLE_REL.as_posix()}/{INIT_NAME} == {INIT_SOURCE_REL.as_posix()}); "
        f"top-level {BUNDLE_REL.as_posix()}/ is exactly {{{INIT_NAME}}}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
